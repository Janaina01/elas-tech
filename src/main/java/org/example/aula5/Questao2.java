package org.example.aula5;

public class Questao2 {
    public static void main(String[] args) {

        for (int i = 1; i <= 15; i++) {
            if (i % 2 == 0) {
                System.out.println(i + " é par.");
            } else {
                System.out.println(i + " é impar.");
            }
        }
    }
}
