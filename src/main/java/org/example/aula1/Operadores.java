package org.example.aula1;

public class Operadores {
    static void main() {
        int numero1 = 10;
        int numero2 = 3;
        int resultado = 0;

        resultado = numero1 - numero2;
        System.out.println(resultado);

        resultado = numero1 / numero2;
        System.out.println(resultado);

        resultado = numero1 * numero2;
        System.out.println(resultado);

        resultado = numero1 % numero2;
        System.out.println(resultado);
    }
}